def _repo(tmp: Path) -> Path:
    repo = tmp / "repo"
    repo.mkdir()
    (repo / "requirements-runtime.txt").write_text("pillow>=10.0\nscapy>=2.6,<3\nrequests>=2.32\nstreamlit>=1.66\n")
    (repo / "requirements.lock").write_text(LOCK)
    (repo / "requirements-build.lock").write_text(BUILD_LOCK)
    (repo / "go.mod").write_text("module github.com/acme/self\n\ngo 1.22\n")
    return repo


def _syft_outputs(tmp: Path) -> Path:
    """What Syft 1.57 writes for such a repository: range guesses, a SHA-pinned action named by its tag comment,
    the manifests as ``type: file`` components, and the project's own Go module."""
    comps = [
        {"bom-ref": "s1", "type": "library", "name": "pillow", "version": "10.0", "purl": "pkg:pypi/pillow@10.0"},
        {"bom-ref": "s2", "type": "library", "name": "scapy", "version": "2.6", "purl": "pkg:pypi/scapy@2.6"},
        {"bom-ref": "s3", "type": "library", "name": "tqdm", "version": "4.66", "purl": "pkg:pypi/tqdm@4.66"},
        {"bom-ref": "s4", "type": "library", "name": "actions/checkout", "version": "v5",
         "purl": "pkg:github/actions/checkout@v5", "cpe": "cpe:2.3:a:actions:checkout:v5:*:*:*:*:*:*:*"},
        {"bom-ref": "s5", "type": "file", "name": "/requirements-runtime.txt"},
        {"bom-ref": "s6", "type": "file", "name": "/.github/workflows/ci.yml"},
        {"bom-ref": "s7", "type": "library", "name": "github.com/acme/self", "version": "UNKNOWN",
         "purl": "pkg:golang/github.com/acme/self"},
    ]
    cdx = tmp / "syft.cdx.json"
    cdx.write_text(json.dumps({"bomFormat": "CycloneDX", "specVersion": "1.6", "components": comps,
                               "metadata": {"component": {"bom-ref": "root", "type": "file", "name": "."}}}))
    native = {"artifacts": [
        {"name": "pillow", "type": "python", "purl": "pkg:pypi/pillow@10.0",
         "metadata": {"versionConstraint": ">=10.0"}},
        {"name": "scapy", "type": "python", "purl": "pkg:pypi/scapy@2.6",
         "metadata": {"versionConstraint": ">=2.6,<3"}},
        {"name": "tqdm", "type": "python", "purl": "pkg:pypi/tqdm@4.66", "metadata": {"versionConstraint": ">=4.66"}},
        {"name": "actions/checkout", "type": "github-action", "version": "v5", "purl": "pkg:github/actions/checkout@v5",
         "metadata": {"value": "actions/checkout@fbc6f3992d24b796d5a048ff273f7fcc4a7b6c09", "comment": "v5"}},
    ]}
    Path(str(cdx) + ".native.json").write_text(json.dumps(native))
    return cdx


def _cdxgen_output(tmp: Path) -> Path:
    path = tmp / "cdxgen.cdx.json"
    path.write_text(json.dumps({"bomFormat": "CycloneDX", "specVersion": "1.6", "components": [
        {"bom-ref": "c1", "type": "application", "name": "checkout", "group": "actions",
         "version": "fbc6f3992d24b796d5a048ff273f7fcc4a7b6c09",
         "purl": "pkg:github/actions/checkout@fbc6f3992d24b796d5a048ff273f7fcc4a7b6c09"},
    ]}))
    return path


