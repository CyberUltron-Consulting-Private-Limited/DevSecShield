def _syft():
    import os

    return os.environ.get("SYFT_BIN") or shutil.which("syft")


@pytest.mark.skipif(not _syft(), reason="syft not on PATH (CI installs the image's version: .github/ci/install-sbom-tools.sh)")
def test_real_syft_reads_uv_lock_and_not_pip_locks(tmp_path):
    """Syft reads uv.lock and poetry.lock itself; pip-format *.lock files are ours (pip_lock.py)."""
    (tmp_path / "pyproject.toml").write_text('[project]\nname = "demo"\nversion = "0.1.0"\n'
                                             'dependencies = ["idna>=3"]\n')
    (tmp_path / "uv.lock").write_text(
        'version = 1\nrequires-python = ">=3.12"\n\n'
        '[[package]]\nname = "demo"\nversion = "0.1.0"\nsource = { editable = "." }\n'
        'dependencies = [{ name = "idna" }]\n\n'
        '[[package]]\nname = "idna"\nversion = "3.10"\nsource = { registry = "https://pypi.org/simple" }\n')
    (tmp_path / "requirements.lock").write_text("certifi==2026.10.23\n    # via -r requirements.txt\n")
    from helpers.tools.sca_sbom_agent.syft import syft_command, syft_env

    out = tmp_path / "out.cdx.json"
    subprocess.run(syft_command(tmp_path, out), env=syft_env(), check=True, capture_output=True, timeout=300)
    purls = {c.get("purl") for c in json.loads(out.read_text())["components"]}
    assert "pkg:pypi/idna@3.10" in purls
    assert "pkg:pypi/certifi@2026.10.23" not in purls
    from helpers.tools.sca_sbom_agent.pip_lock import lock_document

    assert [c["purl"] for c in lock_document(tmp_path)["components"]] == ["pkg:pypi/certifi@2026.10.23"]
