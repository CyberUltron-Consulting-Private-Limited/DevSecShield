def template_text(name: str) -> str | None:
    if name == "sudoers":
        return SUDOERS
    if name == "k8s-tier1":
        return K8S_TIER1
    if name == "k8s-tier2":
        return K8S_TIER2
    if name.startswith("grant-"):
        return DB_GRANTS.get(name[len("grant-"):])
    return None


def zeroshield_account_id() -> str | None:
    """ZeroShield's AWS account (the principal customers trust), from CBOM_AWS_PRINCIPAL_ARN."""
    arn = os.environ.get("CBOM_AWS_PRINCIPAL_ARN", "")
    match = re.match(r"^arn:aws(?:-cn|-us-gov)?:(?:iam|sts)::(\d{12}):", arn)
    return match.group(1) if match else None


def cloudformation_template(external_id: str, scope: str) -> str:
    if not re.fullmatch(r"zs-ext-[A-Z0-9]{4}(-[A-Z0-9]{4}){3}", external_id):
        raise ValueError("unexpected external id format")
    account = zeroshield_account_id() or "000000000000"
    deny = "\n".join(f"                  - {action}" for action in DENY_ACTIONS)
    header = (
        "# Deploy as a CloudFormation StackSet to every member account (service-managed permissions).\n"
        if scope == "organization"
        else "# Deploy as a CloudFormation stack in the account you want ZeroShield to inventory.\n"
    )
    placeholder = (
        "# NOTE: ZeroShieldAccountId is a placeholder (CBOM_AWS_PRINCIPAL_ARN is not configured on the server).\n"
        if account == "000000000000"
        else ""
    )
    return f"""{header}{placeholder}AWSTemplateFormatVersion: "2010-09-09"
Description: >-
  ZeroShield CBOM read-only cloud scanner role. Grants the AWS-managed SecurityAudit
  policy and explicitly denies every data-plane read and key-use action, so ZeroShield
  can inventory cryptographic configuration but can never read secrets, objects or
  use keys.

Parameters:
  ZeroShieldAccountId:
    Type: String
    Default: "{account}"
    AllowedPattern: "^[0-9]{{12}}$"
  ExternalId:
    Type: String
    Default: "{external_id}"
    NoEcho: true
    AllowedPattern: "^[A-Za-z0-9+=,.@:/_-]+$"
  RoleName:
    Type: String
    Default: ZeroShieldCBOMReader

Resources:
  ZeroShieldCBOMReaderRole:
    Type: AWS::IAM::Role
    Properties:
      RoleName: !Ref RoleName
      Description: ZeroShield CBOM cloud scanner (SecurityAudit minus data-plane and key-use actions)
      MaxSessionDuration: 3600
      AssumeRolePolicyDocument:
        Version: "2012-10-17"
        Statement:
          - Effect: Allow
            Principal:
              AWS: !Sub "arn:${{AWS::Partition}}:iam::${{ZeroShieldAccountId}}:root"
            Action: sts:AssumeRole
            Condition:
              StringEquals:
                sts:ExternalId: !Ref ExternalId
      ManagedPolicyArns:
        - !Sub "arn:${{AWS::Partition}}:iam::aws:policy/SecurityAudit"
      Policies:
        - PolicyName: ZeroShieldCBOMReaderDeny
          PolicyDocument:
            Version: "2012-10-17"
            Statement:
              - Sid: DenyKeyUseAndDataPlaneReads
                Effect: Deny
                Action:
{deny}
                Resource: "*"

Outputs:
  RoleArn:
    Description: Paste this ARN into ZeroShield.
    Value: !GetAtt ZeroShieldCBOMReaderRole.Arn
"""
