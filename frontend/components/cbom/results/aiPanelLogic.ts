/**
 * Pure rules of the CBOM AI remediation panel (CB-38 PR-6): when it shows, what its badge and egress note say, how a
 * citation id becomes a chip label, and what each outcome tells the user. No React, no network: tested with tsx.
 */
import type { CbomAiAnswer, CbomAiMode, CbomAiStatus } from "@/utils/backend_api";

export const MAX_QUESTION = 500;

/** The panel exists only when the backend says the assistant is available; loading, errors and "unavailable" all
 * render nothing (not a disabled button). */
export function aiPanelVisible(status: CbomAiStatus | null | undefined): boolean {
  return status?.available === true;
}

/** Where the assistant sends data, in the user's words. */
export function egressNote(status: CbomAiStatus | null | undefined): string {
  if (!status?.available) return "";
  const host = status.egress?.[0]?.host;
  if (status.provider === "bedrock") {
    const region = status.region ?? "";
    const target = host ?? `bedrock-runtime.${region}.amazonaws.com`;
    return `Uses AWS Bedrock (${region}, ${status.model ?? ""}) · outbound HTTPS to ${target} only`;
  }
  return `Uses ${status.model ?? "the model"} on your deployment${host ? ` (${host})` : ""} · nothing leaves your network`;
}

/** The badge under an answer: which model wrote it, where, and the KB version it was checked against. */
export function answerBadge(answer: Pick<CbomAiAnswer, "model" | "kb_version" | "provider" | "region">): string {
  const where = answer.provider === "bedrock" ? `on AWS Bedrock (${answer.region ?? ""})` : "on your deployment";
  return `Generated by ${answer.model} ${where} · checked against KB ${answer.kb_version}`;
}

/** "K1.s2" -> "K1 WEAK_CIPHER · step 2 (nginx)"; an id the answer did not list stays as it is. */
export function citationLabel(id: string, items: { id: string; label: string }[] | undefined): string {
  return items?.find((i) => i.id === id)?.label ?? id;
}

export type OutcomeNote = { tone: "info" | "warn"; text: string } | null;

/** What the user is told besides the answer itself. */
export function outcomeNote(answer: CbomAiAnswer | null | undefined): OutcomeNote {
  if (!answer) return null;
  if (answer.status === "withheld") {
    return {
      tone: "warn",
      text: `${answer.withheld_reason || "AI answer withheld"}. Showing the knowledge-base steps instead (the remediation above is unchanged).`,
    };
  }
  if (answer.status === "timeout") return { tone: "warn", text: "AI assistant did not answer in time. The knowledge-base remediation above is unaffected." };
  if (answer.status === "error") return { tone: "warn", text: "AI assistant is unavailable right now. The knowledge-base remediation above is unaffected." };
  return null;
}

export function canAsk(mode: CbomAiMode, question: string): boolean {
  if (mode !== "question") return true;
  const q = question.trim();
  return q.length > 0 && q.length <= MAX_QUESTION;
}
