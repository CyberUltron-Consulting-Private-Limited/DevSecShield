MEM_FLOOR_MB = 1536          # keep >= 1.5 GB available (TEAM-PROCESS, DA §4.1)
WAVE_MEM_MB = {"core": 400, "db": 700, "run2": 20, "hsm": 0, "code": 0, "k8s": 900, "tools": 150}
LOCK_DIR = Path(os.environ.get("CB_LAB_LOCKS", "/home/claude/round6/locks"))
CACHE = Path(os.environ.get("CB_LAB_CACHE", str(HERE / ".work" / "cache")))
BENCH = S.by_id("code-cryptoapi-bench")


class LabError(Exception):
    def __init__(self, msg: str, code: int = 1):
        super().__init__(msg)
        self.code = code


def log(msg: str) -> None:
    print(f"[cb02 {time.strftime('%H:%M:%S', time.gmtime())}Z] {msg}", file=sys.stderr, flush=True)


def run(cmd: list[str], *, check: bool = True, capture: bool = True, env: dict | None = None,
        timeout: int | None = None) -> subprocess.CompletedProcess:
    res = subprocess.run(cmd, capture_output=capture, text=True, env={**os.environ, **(env or {})}, timeout=timeout)
    if check and res.returncode != 0:
        tail = (res.stderr or res.stdout or "")[-1500:] if capture else ""
        raise LabError(f"{' '.join(cmd[:4])} ... failed ({res.returncode}): {tail}")
    return res


# ------------------------------------------------------------------ compose file (generated from labspec)
def compose_text() -> str:
    """compose.yml, generated from the catalogue so an address or a profile exists exactly once."""
    out = ["# GENERATED by `python3 e2e/cbom/lab/gen.py compose` from labspec.py; edit labspec.py, not this file.",
           "# Project cb02-lab: every container is named cb02-<target>; waves are compose profiles.",
           "# CB_LAB_DIR (= <run>/lab) and CB_RUN_DIR are set by gen.py up; the network is created by gen.py up",
           "# or by the stack (CB-03), never by compose (external).",
           f"name: {PROJECT}", "",
           "x-target: &target",
           "  image: ${CB02_TARGET_IMAGE:-" + IMAGES["target"] + "}",
           "  restart: \"no\"",
           "  cap_drop: [ALL]",
           "  security_opt: [\"no-new-privileges:true\"]",
           "  mem_limit: 64m",
           "  pids_limit: 128",
           "  labels: {com.zeroshield.cbom-lab: cb02}",
           "",
           "networks:",
           "  lab:",
           f"    name: {S.NETWORK['name']}",
           "    external: true",
           "",
           "services:"]
    for t in S.TARGETS:
        if not t.get("ip"):
            continue
        tid = t["id"]
        aliases = [f"{tid}.lab", *t.get("sni", []), *t.get("aliases", [])]
        out.append(f"  {tid}:")
        vols = [f"${{CB_LAB_DIR:?run gen.py up}}/targets/{tid}:/lab:ro"]
        if t["kind"] in ("postgres", "mysql"):
            image = {"postgres": "postgres:16-alpine@sha256:aa6cb33cf4c19c765cefcf48d96176258800870a9a1e930ad126200f9d825139",
                     "mysql": "mysql:8.4@sha256:a81d043930e51745522bd5c430961cf8286f0a23f0a9a2a6e0108f7ea71b0902"}[t["kind"]]
            out += [f"    image: ${{CB_LAB_REGISTRY:-mirror.gcr.io/library}}/{image}",
                    "    restart: \"no\"", "    security_opt: [\"no-new-privileges:true\"]",
                    f"    mem_limit: {'96m' if t['kind'] == 'postgres' else '400m'}",
                    "    labels: {com.zeroshield.cbom-lab: cb02}",
                    "    entrypoint: [\"/bin/sh\", \"/lab/start.sh\"]",
                    f"    env_file: [\"${{CB_LAB_DIR:?}}/targets/{tid}/{'pg' if t['kind'] == 'postgres' else 'mysql'}.env\"]"]
            vols.append(f"${{CB_LAB_DIR:?}}/targets/{tid}/initdb:/docker-entrypoint-initdb.d:ro")
            if t["kind"] == "postgres":
                out.append("    tmpfs: [\"/var/lib/postgresql/data:size=96m\"]")
                hc = "pg_isready -h 127.0.0.1 -U postgres"
            else:
                hc = "mysqladmin ping -h 127.0.0.1 --silent"
            out += ["    healthcheck:", f"      test: [\"CMD-SHELL\", \"{hc}\"]",
                    "      interval: 3s", "      timeout: 3s", "      retries: 60"]
        else:
            out.append("    <<: *target")
            if t["kind"] == "listener":
                vols.append("${CB_LAB_DIR:?}/listeners:/logs")
            if t["kind"] == "host":
                vols.append("${CB_LAB_DIR:?}/forcecommand.log:/var/log/cb02/commands.log")
        out += [f"    container_name: cb02-{tid}", f"    profiles: [{t['profile']}]",
                "    volumes:", *[f"      - \"{v}\"" for v in vols],
                "    networks:", "      lab:", f"        ipv4_address: {t['ip']}",
                f"        aliases: [{', '.join(aliases)}]"]
    out += ["  tools:",
            "    image: ${CB02_TOOLS_IMAGE:-" + IMAGES["tools"] + "}",
            "    container_name: cb02-tools",
            "    profiles: [tools]",
            "    restart: \"no\"",
            "    command: [\"sleep\", \"infinity\"]",
            "    user: \"${CB_LAB_UID:-10001}:${CB_LAB_GID:-10001}\"",
            "    environment: {HOME: /tmp}",
            "    security_opt: [\"no-new-privileges:true\"]",
            "    mem_limit: 512m",
            "    labels: {com.zeroshield.cbom-lab: cb02}",
            "    volumes:",
            "      - \"${CB_RUN_DIR:?run gen.py up}:/run-lab:ro\"",
            "      - \"./:/opt/cb02:ro\"",
            "    networks:", "      lab:", f"        ipv4_address: {S.TOOLS_IP}", ""]
    return "\n".join(out)


def cmd_compose(a: argparse.Namespace) -> int:
    text = compose_text()
    if a.check:
        if not COMPOSE.exists() or COMPOSE.read_text() != text:
            raise LabError("compose.yml is not what labspec.py generates: run `gen.py compose`", 2)
        return 0
    COMPOSE.write_text(text)
    log(f"wrote {COMPOSE}")
    return 0


# ------------------------------------------------------------------ environment checks
def mem_available_mb() -> int:
    for line in Path("/proc/meminfo").read_text().splitlines():
        if line.startswith("MemAvailable:"):
            return int(line.split()[1]) // 1024
    return 0


def check_memory(waves: list[str], when: str) -> None:
    need = sum(WAVE_MEM_MB.get(w, 0) for w in waves) if when == "before" else 0
    avail = mem_available_mb()
    if avail - need < MEM_FLOOR_MB:
        raise LabError(f"memory {when} start: {avail} MB available, wave needs ~{need} MB, floor {MEM_FLOOR_MB} MB", 2)
    log(f"memory {when}: {avail} MB available (floor {MEM_FLOOR_MB} MB)")


def git_commit() -> str:
    res = run(["git", "-C", str(HERE), "rev-parse", "HEAD"], check=False)
    dirty = run(["git", "-C", str(HERE), "status", "--porcelain", "--", "."], check=False).stdout.strip()
    return (res.stdout.strip() or "unknown") + ("-dirty" if dirty else "")


def locked(lock: str, cmd: list[str]) -> list[str]:
    path = LOCK_DIR / lock
    return ["flock", str(path), *cmd] if LOCK_DIR.is_dir() and shutil.which("flock") else cmd


def image_exists(ref: str) -> bool:
    return run(["docker", "image", "inspect", ref], check=False).returncode == 0


def cmd_build(a: argparse.Namespace) -> int:
    ca = os.environ.get("CB_LAB_BUILD_CA", "/root/.ccr/ca-bundle.crt")
    proxy = os.environ.get("HTTPS_PROXY") or os.environ.get("https_proxy")
    for name, ref in IMAGES.items():
        if image_exists(ref) and not getattr(a, "force", False):
            continue
        cmd = ["docker", "build", "-f", str(HERE / "images" / f"{name}.Dockerfile"), "-t", ref]
        if proxy:  # a build behind the session's TLS-intercepting proxy: host network + its CA as a build secret
            cmd += ["--network", "host", "--build-arg", f"HTTPS_PROXY={proxy}"]
        if Path(ca).is_file():
            cmd += ["--secret", f"id=build_ca,src={ca}"]
        log(f"building {ref} (docker-build.lock)")
        run(locked("docker-build.lock", [*cmd, str(HERE)]), capture=True)
    return 0


def ensure_network() -> None:
    net = S.NETWORK
    res = run(["docker", "network", "inspect", net["name"]], check=False)
    if res.returncode == 0:
        info = json.loads(res.stdout)[0]
        subnets = [c.get("Subnet") for c in (info.get("IPAM") or {}).get("Config") or []]
        if net["subnet"] not in subnets:
            raise LabError(f"network {net['name']} exists with {subnets}, expected {net['subnet']}", 2)
        return
    log(f"creating network {net['name']} {net['subnet']} (dynamic range {net['ip_range']})")
    run(["docker", "network", "create", "--driver", "bridge", "--subnet", net["subnet"], "--ip-range", net["ip_range"],
         "--gateway", net["gateway"], "--label", "com.zeroshield.cbom-lab=cbom-e2e-net", net["name"]])


def compose(run_dir: Path, *args: str, profiles: list[str]) -> subprocess.CompletedProcess:
    env = {"CB_LAB_DIR": str(run_dir / "lab"), "CB_RUN_DIR": str(run_dir), "CB_LAB_UID": str(os.getuid()),
           "CB_LAB_GID": str(os.getgid())}
    prof = [x for p in profiles for x in ("--profile", p)]
    return run(["docker", "compose", "-f", str(COMPOSE), "-p", PROJECT, *prof, *args], env=env)


def waves_of(a: argparse.Namespace) -> list[str]:
    waves = [w for w in a.wave.split(",") if w]
    for w in waves:
        if w not in S.PROFILES or w == "tools":
            raise LabError(f"unknown wave {w}; known: {', '.join(p for p in S.PROFILES if p != 'tools')}")
    return waves


# ------------------------------------------------------------------ fetch / generate / hash
def cmd_fetch(a: argparse.Namespace) -> int:
    """CryptoAPI-Bench at the pinned commit into the cache (git over the session proxy); verified by commit id."""
    dest = CACHE / f"cryptoapi-bench-{BENCH['commit'][:7]}"
    marker = dest / ".cb02-commit"
    if marker.exists() and marker.read_text().strip() == BENCH["commit"]:
        return 0
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    run(["git", "init", "-q", str(dest)])
    run(["git", "-C", str(dest), "fetch", "-q", "--depth", "1", BENCH["repo"], BENCH["commit"]], timeout=300)
    run(["git", "-C", str(dest), "checkout", "-q", "FETCH_HEAD"])
    head = run(["git", "-C", str(dest), "rev-parse", "HEAD"]).stdout.strip()
    if head != BENCH["commit"]:
        raise LabError(f"CryptoAPI-Bench fetched {head}, pinned {BENCH['commit']}", 2)
    marker.write_text(head + "\n")
    log(f"CryptoAPI-Bench {head[:7]} in {dest}")
    return 0


oracle_hash = oraclefmt.oracle_hash
oracle_sums = oraclefmt.oracle_sums


def cmd_hash(a: argparse.Namespace) -> int:
    run_dir = Path(a.run_dir).resolve()
    h = oracle_hash(run_dir)
    if a.verify:
        if a.verify != h:
            log(f"oracle changed: recorded {a.verify[:16]}..., now {h[:16]}... (rule O-5: start a new run)")
            print(json.dumps({"oracle_sha256": h, "recorded": a.verify, "agree": False}))
            return 2
        print(json.dumps({"oracle_sha256": h, "agree": True}))
        return 0
    (run_dir / "oracle" / "SHA256SUMS").write_text(oracle_sums(run_dir))
    gen = json.loads((run_dir / "lab" / "gen.json").read_text())
    gen["oracle_sha256"] = h
    (run_dir / "lab" / "gen.json").write_text(json.dumps(gen, indent=1, sort_keys=True) + "\n")
    print(json.dumps({"oracle_sha256": h}))
    return 0


def generate(run_dir: Path, waves: list[str], variant: str | None, only: str | None = None) -> None:
    facts = run_dir / "oracle" / "facts" / "index.json"
    if facts.exists():
        made = set(json.loads((run_dir / "lab" / "gen.json").read_text())["profiles"])
        if not set(waves) <= made:
            raise LabError(f"{run_dir} was generated for {sorted(made)}; wave {waves} needs a new run directory")
        return
    run_dir.mkdir(parents=True, exist_ok=True)
    run_dir.chmod(0o700)
    if "code" in waves:
        cmd_fetch(argparse.Namespace())
    cache_mount = ["-v", f"{CACHE}:/cache:ro"] if CACHE.exists() else []
    cmd = ["docker", "run", "--rm", "--network", "none", "--user", f"{os.getuid()}:{os.getgid()}", "-e", "HOME=/tmp",
           "-v", f"{run_dir}:/out", "-v", f"{HERE}:/opt/cb02:ro", *cache_mount, IMAGES["tools"],
           "python3", "/opt/cb02/labgen.py", "--out", "/out", "--profiles", ",".join(waves), "--wave", ",".join(waves),
           "--commit", git_commit(), *(["--cache", "/cache"] if cache_mount else []),
           *(["--variant", variant] if variant else []), *(["--only", only] if only else [])]
    log(f"generating lab + oracle for {waves}{' variant ' + variant if variant else ''}")
    res = run(cmd)
    (run_dir / "lab" / "gen.log").write_text(res.stdout + res.stderr)
    cmd_hash(argparse.Namespace(run_dir=str(run_dir), verify=None))


# ------------------------------------------------------------------ up / down / status
def wave_services(run_dir: Path, waves: list[str]) -> list[str]:
    gj = json.loads((run_dir / "lab" / "gen.json").read_text())
    step = gj.get("current_step", "run1")
    idx = json.loads((run_dir / "oracle" / ("facts" if step == "run1" else f"{step}/facts") / "index.json").read_text())
    return [t["target"] for t in idx["targets"] if t["profile"] in waves and t.get("container")]


def cmd_up(a: argparse.Namespace) -> int:
    run_dir = Path(a.run_dir).resolve()
    waves = waves_of(a)
    if "k8s" in waves:
        raise LabError("the k8s wave is not part of this lab build (see README: deferred, disk)")
    check_memory(waves, "before")
    cmd_build(argparse.Namespace(force=False))
    ensure_network()
    generate(run_dir, waves, a.variant, a.only)
    services = wave_services(run_dir, waves)
    if services:
        log(f"starting {len(services)} targets + cb02-tools ({','.join(waves)})")
        compose(run_dir, "up", "-d", "--wait", "--wait-timeout", "180", *services, "tools",
                profiles=[*waves, "tools"])
    else:
        compose(run_dir, "up", "-d", "--wait", "tools", profiles=["tools"])
    check_memory([], "after")
    print(json.dumps({"run_dir": str(run_dir), "waves": waves, "targets": services,
                      "oracle_sha256": oracle_hash(run_dir)}))
    return 0


def lab_containers() -> list[str]:
    res = run(["docker", "ps", "-a", "--filter", "label=com.zeroshield.cbom-lab=cb02", "--format", "{{.Names}}"],
              check=False)
    return sorted(n for n in res.stdout.split() if n.startswith("cb02-"))


def cmd_down(a: argparse.Namespace) -> int:
    names = lab_containers()
    if names:
        # compose waits for each removal (a bare `docker rm -f` of many containers raced with the next `up` in the
        # first 3-cycle run: "removal ... already in progress"); then sweep anything compose did not own, and poll.
        env = {"CB_LAB_DIR": "/nonexistent", "CB_RUN_DIR": "/nonexistent"}
        prof = [x for p in S.PROFILES for x in ("--profile", p)]
        run(["docker", "compose", "-f", str(COMPOSE), "-p", PROJECT, *prof, "down", "-v", "--remove-orphans",
             "--timeout", "5"], env=env, check=False)
        left = lab_containers()
        if left:
            run(["docker", "rm", "-f", "-v", *left], check=False)
        deadline = time.time() + 60
        while lab_containers() and time.time() < deadline:
            time.sleep(1)
        if lab_containers():
            raise LabError(f"containers still present after down: {lab_containers()}")
        log(f"removed {len(names)} containers")
    res = run(["docker", "network", "inspect", S.NETWORK["name"]], check=False)
    if res.returncode == 0:
        info = json.loads(res.stdout)[0]
        mine = (info.get("Labels") or {}).get("com.zeroshield.cbom-lab") == "cbom-e2e-net"
        if not info.get("Containers") and mine:
            run(["docker", "network", "rm", S.NETWORK["name"]])
            log("removed network (nothing else attached)")
        else:
            log("network kept (other endpoints attached, or created by the stack)")
    return 0


def cmd_status(a: argparse.Namespace) -> int:
    res = run(["docker", "ps", "-a", "--filter", "label=com.zeroshield.cbom-lab=cb02", "--format",
               "{{.Names}}\t{{.Status}}"], check=False)
    rows = [dict(zip(("container", "status"), line.split("\t", 1))) for line in res.stdout.splitlines() if line]
    out: dict = {"containers": rows, "memory_available_mb": mem_available_mb()}
    if a.run_dir:
        run_dir = Path(a.run_dir).resolve()
        if (run_dir / "lab" / "lab.json").exists():
            out["lab"] = json.loads((run_dir / "lab" / "lab.json").read_text())
            out["oracle_sha256"] = oracle_hash(run_dir)
    print(json.dumps(out, indent=1))
    return 0


def cmd_selfcheck(a: argparse.Namespace) -> int:
    import labcheck
    return labcheck.main(Path(a.run_dir).resolve(), only=a.only)


def cmd_mutate(a: argparse.Namespace) -> int:
    import labmutate
    return labmutate.main(Path(a.run_dir).resolve(), a.step)


def cmd_negative(a: argparse.Namespace) -> int:
    import labnegative
    return labnegative.main(Path(a.run_dir_base).resolve())


def main(argv: list[str] | None = None) -> int:
    if sys.version_info < (3, 11):
        print("gen.py needs Python >= 3.11", file=sys.stderr)
        return 1
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("up")
    p.add_argument("--run-dir", required=True)
    p.add_argument("--wave", default="core")
    p.add_argument("--variant")
    p.add_argument("--only")
    p.set_defaults(fn=cmd_up)
    p = sub.add_parser("selfcheck")
    p.add_argument("--run-dir", required=True)
    p.add_argument("--only")
    p.set_defaults(fn=cmd_selfcheck)
    p = sub.add_parser("mutate")
    p.add_argument("--run-dir", required=True)
    p.add_argument("--step", required=True, choices=["run2"])
    p.set_defaults(fn=cmd_mutate)
    p = sub.add_parser("down")
    p.add_argument("--run-dir")
    p.set_defaults(fn=cmd_down)
    p = sub.add_parser("status")
    p.add_argument("--run-dir")
    p.set_defaults(fn=cmd_status)
    p = sub.add_parser("hash")
    p.add_argument("--run-dir", required=True)
    p.add_argument("--verify")
    p.set_defaults(fn=cmd_hash)
    p = sub.add_parser("build")
    p.add_argument("--force", action="store_true")
    p.set_defaults(fn=cmd_build)
    p = sub.add_parser("fetch")
    p.set_defaults(fn=cmd_fetch)
    p = sub.add_parser("compose")
    p.add_argument("--check", action="store_true")
    p.set_defaults(fn=cmd_compose)
    p = sub.add_parser("negative")
    p.add_argument("--run-dir-base", required=True)
    p.set_defaults(fn=cmd_negative)
    a = ap.parse_args(argv)
    try:
        return a.fn(a)
    except LabError as e:
        log(f"error: {e}")
        return e.code
    except subprocess.TimeoutExpired as e:
        log(f"timeout: {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
