"""Report generator for the differential gate (``tests/test_differential.py``).

The gate ASSERTS recall thresholds; this renders the same numbers (plus
precision and the concrete missed-item work-lists) into a human-readable
``differential_report.md`` and a machine-readable ``differential_report.json``.

It **reuses the gate's exact methodology** — categorization, oracle routing
(model→Cisco, provider/framework→Trusera), thresholds, fixtures — by importing
them from :mod:`test_differential`. So the report can never drift from what CI
enforces: same scan, same sets, same routing. Regenerate with::

    uv run python tests/differential.py

Determinism & async: our engine scan is SYNCHRONOUS (``scan_repo`` returns a
finished ``ScanResult``); there is no job to await. If ever driven through the
DevSecShield Celery worker, poll for terminal job state — never sleep
(skill-condition-based-waiting). See the gate module's docstring for the full
methodology and the model→Cisco rationale (Trusera types SDK/provider names as
``machine-learning-model`` and extracts zero real model identifiers).
"""

from __future__ import annotations

import json
from pathlib import Path

import test_differential as gate  # the gate IS the methodology — reuse, don't fork

_HERE = Path(__file__).resolve().parent
FIXTURES = ("synthetic", "trusera-demo", "chroma")
COMMITTED = ("synthetic", "trusera-demo")  # present in a fresh checkout
CATEGORIES = ("provider", "framework", "model")

REPORT_MD = _HERE / "differential_report.md"
REPORT_JSON = _HERE / "differential_report.json"


def _oracle_tool(category: str) -> str:
    """Which oracle the gate measures a category against."""
    return "cisco" if category == "model" else "trusera"


def _present(fixture: str) -> bool:
    return (_HERE / "fixtures" / fixture).is_dir()


def build() -> dict:
    """fixture -> category -> metrics dict, over available fixtures.

    Scans each present fixture ONCE (``gate._our``) and reads both oracles
    (``gate._trusera`` / ``gate._cisco``), then applies the gate's per-category
    oracle routing. Absent fixtures (the git-ignored chroma clone in CI) are
    omitted.
    """
    out: dict[str, dict[str, dict]] = {}
    for fixture in FIXTURES:
        if not _present(fixture):
            continue
        ours = gate._our(fixture)  # one scan → {provider, framework, model} sets
        oracles = {"trusera": gate._trusera(fixture), "cisco": gate._cisco(fixture)}
        per_cat: dict[str, dict] = {}
        for cat in CATEGORIES:
            tool = _oracle_tool(cat)
            o_set = oracles[tool][cat]
            u_set = ours[cat]
            inter = u_set & o_set
            recall = len(inter) / len(o_set) if o_set else None
            precision = len(inter) / len(u_set) if u_set else None
            floor = gate.THRESHOLDS[cat]
            per_cat[cat] = {
                "oracle_tool": tool,
                "recall": recall,
                "precision": precision,
                "threshold": floor,
                "passed": (recall is not None and recall >= floor),
                "n_oracle": len(o_set),
                "n_ours": len(u_set),
                "n_match": len(inter),
                "missed": sorted(o_set - u_set),
                "extra": sorted(u_set - o_set),
            }
        out[fixture] = per_cat
    return out


def _fmt(x: float | None) -> str:
    return "  —  " if x is None else f"{x:.2f}"


def render_md(matrix: dict) -> str:
    L: list[str] = []
    L.append("# AI-BOM differential detection report")
    L.append("")
    L.append(
        "_Generated by `tests/differential.py`, reusing the gate methodology in "
        "`tests/test_differential.py` (so these numbers are exactly what CI "
        "enforces). OUR scanner: `aibom.scan_repo`, level 4. Recall is gated; "
        "precision is reported. Advisory: a parity gap is evidence, not ground "
        "truth — only `synthetic` has hand-labelled ground truth "
        "(`fixtures/synthetic/GROUND_TRUTH.md`)._"
    )
    L.append("")
    L.append(
        "**Oracle routing** — `model` recall is measured vs **Cisco** (the only "
        "oracle that extracts real model identifiers like `gpt-4o`); `provider` "
        "and `framework` vs **Trusera**. Thresholds: "
        + ", ".join(f"`{k}` ≥ {v:.2f}" for k, v in gate.THRESHOLDS.items())
        + "."
    )
    L.append("")

    # Headline verdict.
    reds = [
        (fx, cat)
        for fx, cats in matrix.items()
        for cat, m in cats.items()
        if not m["passed"]
    ]
    L.append("## Verdict")
    L.append("")
    if reds:
        L.append(f"🔴 **{len(reds)} gate(s) RED** "
                 f"(of {sum(len(c) for c in matrix.values())} measured):")
        L.append("")
        for fx, cat in reds:
            m = matrix[fx][cat]
            L.append(
                f"- `{fx}/{cat}` — recall {_fmt(m['recall'])} < {m['threshold']:.2f} "
                f"(vs {m['oracle_tool']}; missed {len(m['missed'])}/{m['n_oracle']})"
            )
        L.append("")
        L.append(
            "> **`model` is now GREEN** across the gated fixtures: the model-ref "
            "scanner reads inline references (`model=\"gpt-4o\"`) from source. The "
            "residual REDs are `chroma` **provider/framework** — that repo declares "
            "deps in `pyproject`/`package.json` (not `requirements.txt`), so the "
            "requirements-only dependency scan still under-detects them. That is the "
            "next gap (deps-in-code); these gates go green when manifest coverage "
            "extends beyond `requirements.txt`."
        )
    else:
        L.append("🟢 **All measured gates GREEN.**")
    L.append("")

    # Per-fixture tables.
    for fixture in FIXTURES:
        if fixture not in matrix:
            continue
        tag = "" if fixture in COMMITTED else "  _(local clone — SKIPPED in CI)_"
        L.append(f"## `{fixture}`{tag}")
        L.append("")
        L.append(
            "| category | vs | recall | precision | oracle | ours | matched | gate |"
        )
        L.append("|---|---|---|---|---|---|---|---|")
        for cat in CATEGORIES:
            m = matrix[fixture][cat]
            verdict = "🟢" if m["passed"] else "🔴"
            L.append(
                f"| {cat} | {m['oracle_tool']} | {_fmt(m['recall'])} "
                f"(≥{m['threshold']:.2f}) | {_fmt(m['precision'])} | {m['n_oracle']} "
                f"| {m['n_ours']} | {m['n_match']} | {verdict} |"
            )
        L.append("")
        for cat in CATEGORIES:
            m = matrix[fixture][cat]
            if m["missed"]:
                n = len(m["missed"])
                shown = ", ".join(f"`{x}`" for x in m["missed"][:20])
                more = f" (+{n - 20} more)" if n > 20 else ""
                L.append(
                    f"- **{cat} missed** ({n}, vs {m['oracle_tool']}): {shown}{more}"
                )
        L.append("")
    return "\n".join(L).rstrip() + "\n"


def main() -> None:
    matrix = build()
    REPORT_MD.write_text(render_md(matrix))
    REPORT_JSON.write_text(json.dumps(matrix, indent=2, sort_keys=True) + "\n")
    print(render_md(matrix))


if __name__ == "__main__":
    main()
