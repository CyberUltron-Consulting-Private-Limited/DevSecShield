#!/usr/bin/env python3
"""CB-02 lab CLI, the interface CB-01's gate calls (cbom/INTERFACES.md v1 §3 plus the CB-02 v2 section).

    python3 e2e/cbom/lab/gen.py up        --run-dir RUN [--wave core[,db,hsm,code,run2]] [--variant V]
    python3 e2e/cbom/lab/gen.py selfcheck --run-dir RUN
    python3 e2e/cbom/lab/gen.py mutate    --run-dir RUN --step run2
    python3 e2e/cbom/lab/gen.py down      [--run-dir RUN]
    python3 e2e/cbom/lab/gen.py status    [--run-dir RUN]
    python3 e2e/cbom/lab/gen.py hash      --run-dir RUN [--verify SHA256]
    python3 e2e/cbom/lab/gen.py build | fetch | compose [--check] | negative --run-dir-base DIR

Exit codes: 0 ok; 2 lab bug (a target disagrees with its oracle, an oracle changed, memory below the floor);
1 anything else. Host side: Python >= 3.11 and the docker CLI. Generation runs inside the cb02-lab/tools image
(labgen.py), so the host needs neither OpenSSL 3.5 nor Java. No command prints a secret.
"""
