#!/usr/bin/env bash
# scan_node_image.sh - release the CBOM scan-node image as a file customers can load without registry access.
#
#   scan_node_image.sh build <version>   build zeroshield/cbom-scan-node:<version> from scan_node/, then
#                                        docker save | gzip -> dist/scan-node/scan-node-<version>.tar.gz plus
#                                        scan-node-<version>.tar.gz.sha256. <version>: a digit, then up to 18 digits,
#                                        letters, dots or dashes (e.g. 1.1.0, 2.0.0-rc.1), what the node reports
#   scan_node_image.sh lock              regenerate scan_node/requirements.lock (every package, transitive ones
#                                        included, pinned with sha256 hashes) from scan_node/requirements.txt; the
#                                        image build refuses a lock that does not match requirements.txt
#
# Customer side (documented in scan_node/README.md):
#   sha256sum -c scan-node-<version>.tar.gz.sha256 && docker load -i scan-node-<version>.tar.gz
#
# Env: SCAN_NODE_IMAGE (default zeroshield/cbom-scan-node: the name the archive loads as, which the Add scan node
#      wizard, the Helm chart and the OVA/AMI kits use), OUT_DIR (default dist/scan-node),
#      BASE_IMAGE (passed to the Dockerfile, e.g. a python:3.12-slim that trusts a TLS-intercepting proxy's CA).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
IMAGE="${SCAN_NODE_IMAGE:-zeroshield/cbom-scan-node}"
OUT_DIR="${OUT_DIR:-${REPO_ROOT}/dist/scan-node}"

# The versions the node reports (scan_node/zs_scan_node/__init__.py _VERSION: "<version>+<12-character commit>" fits
# its 32-character column); for anything else it reports its built-in version, so such an image is refused.
NODE_VERSION_RE="^[0-9][0-9A-Za-z.-]{0,18}$"

log() { printf '[scan_node_image %s] %s\n' "$(date -u +%H:%M:%S)" "$*"; }
die() { printf '[scan_node_image] ERROR: %s\n' "$*" >&2; exit 1; }

cmd_lock() {
  command -v uv >/dev/null 2>&1 || die "uv is required (https://docs.astral.sh/uv/)"
  local out="${REPO_ROOT}/scan_node/requirements.lock" body
  body="$(mktemp)"
  (cd "${REPO_ROOT}/scan_node" && uv pip compile requirements.txt --generate-hashes --universal \
    --python-version 3.12 --no-header --quiet -o "${body}")
  {
    printf '# Generated by scripts/release/scan_node_image.sh lock from scan_node/requirements.txt. Do not edit.\n'
    printf '# Installed with pip --require-hashes: every package is pinned and hash-checked.\n'
    cat "${body}"
  } >"${out}.part"
  rm -f "${body}"
  mv "${out}.part" "${out}"
  log "wrote ${out} ($(grep -c '==' "${out}") packages)"
}

cmd_build() {
  local version=${1:?usage: scan_node_image.sh build <version>}
  [[ "${version}" =~ ${NODE_VERSION_RE} ]] ||
    die "invalid version: ${version}: the scan node reports only a version of 1-19 characters that starts with a" \
      "digit (digits, letters, dots, dashes; e.g. 1.1.0 or 2.0.0-rc.1) and would report its built-in one instead"
  local ref="${IMAGE}:${version}" archive="${OUT_DIR}/scan-node-${version}.tar.gz" sha
  local -a args=()
  [[ -n "${BASE_IMAGE:-}" ]] && args+=(--build-arg "BASE_IMAGE=${BASE_IMAGE}")
  # Build identity (CB-03): the node reports <version>+<12-character commit> to ZeroShield (ZS_NODE_VERSION,
  # ZS_NODE_BUILD). A tree with uncommitted or untracked changes claims no commit.
  sha="$(git -C "${REPO_ROOT}" rev-parse HEAD 2>/dev/null || true)"
  [[ "${sha}" =~ ^[0-9a-f]{40}$ ]] || { log "WARNING: no git commit: the image reports no build"; sha=""; }
  if [[ -n "${sha}" && -n "$(git -C "${REPO_ROOT}" status --porcelain --untracked-files=normal 2>/dev/null)" ]]; then
    log "WARNING: uncommitted changes at ${sha:0:12}: the image reports no build"
    sha=""
  fi
  log "building ${ref} (build ${sha:-unknown})"
  docker buildx build --load --provenance=false "${args[@]}" --build-arg "ZS_NODE_BUILD=${sha}" \
    --build-arg "ZS_NODE_VERSION=${version}" \
    --label "org.opencontainers.image.version=${version}" \
    --label "org.opencontainers.image.revision=${sha:-unknown}" \
    -t "${ref}" "${REPO_ROOT}/scan_node"
  # Nothing secret in the image: no env file, key or node state.
  if docker run --rm --network none --entrypoint find "${ref}" /opt/zs-scan-node /var/lib/zs-node \
    \( -name '.env' -o -name '.env.*' -o -name '*.pem' -o -name '*.key' -o -name 'state.json' \) -print | grep -q .; then
    die "${ref} contains an env file, a key or node state"
  fi
  docker run --rm --network none --entrypoint python "${ref}" -c "import zs_scan_node.agent" ||
    die "${ref}: the agent does not import"
  mkdir -p "${OUT_DIR}"
  log "saving ${archive}"
  docker save "${ref}" | gzip -9 >"${archive}.part"
  mv "${archive}.part" "${archive}"
  (cd "${OUT_DIR}" && sha256sum "$(basename "${archive}")" >"$(basename "${archive}").sha256")
  log "done: $(du -h "${archive}" | cut -f1) $(cat "${archive}.sha256")"
}

case "${1:-}" in
  build) shift; cmd_build "$@" ;;
  lock) cmd_lock ;;
  *) sed -n '2,17p' "${BASH_SOURCE[0]}"; [[ -z "${1:-}" || "$1" == -h || "$1" == --help ]] || exit 1 ;;
esac
