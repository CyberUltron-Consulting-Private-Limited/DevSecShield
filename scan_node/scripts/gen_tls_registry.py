"""Generate the TLS registry tables the scan node and the backend share (CB-12).

Inputs (pinned copies in scan_node/tests/fixtures/iana/, see README there):
  * IANA "TLS Cipher Suites" (tls-parameters-4.csv) and "TLS Supported Groups" (tls-parameters-8.csv);
  * `openssl ciphers -V -stdname 'ALL:COMPLEMENTOFALL:@SECLEVEL=0'` of OpenSSL 3.5.7 (the node image's OpenSSL), for the
    OpenSSL name of each suite (s_client reports those).
Outputs:
  * scan_node/zs_scan_node/tls_registry.py   (the node's table; imported by tlsprobe and the collectors)
  * backend/utilities/cbom_sources/data/tls_cipher_suites.json   (the same table for the backend; a test pins equality)

Usage: python3 scan_node/scripts/gen_tls_registry.py   (from the repository root; stdlib only)
"""
from __future__ import annotations

import csv
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIX = ROOT / "scan_node/tests/fixtures/iana"
NODE_OUT = ROOT / "scan_node/zs_scan_node/tls_registry.py"
BACKEND_OUT = ROOT / "backend/utilities/cbom_sources/data/tls_cipher_suites.json"
_CODE = re.compile(r'^"?0x([0-9A-F]{2}),0x([0-9A-F]{2})"?$')
_OPENSSL = re.compile(r"^0x([0-9A-F]{2}),0x([0-9A-F]{2}) - (\S+)\s+- (\S+)")


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def suites() -> dict[int, str]:
    out: dict[int, str] = {}
    with open(FIX / "tls-parameters-4.csv", newline="") as fh:
        for row in csv.DictReader(fh):
            m = _CODE.match(row["Value"].strip())
            name = row["Description"].strip()
            if not m or not name.startswith("TLS_") or name.endswith("_SCSV"):
                continue  # ranges, Unassigned/Reserved, and the two signalling values (not suites)
            out[int(m.group(1) + m.group(2), 16)] = name
    return out


def openssl_names() -> dict[int, tuple[str, str]]:
    out: dict[int, tuple[str, str]] = {}
    for line in (FIX / "openssl-3.5.7-ciphers-V-stdname.txt").read_text().splitlines():
        m = _OPENSSL.match(line.strip())
        if m:
            out[int(m.group(1) + m.group(2), 16)] = (m.group(3), m.group(4))
    return out


def groups() -> dict[int, str]:
    out: dict[int, str] = {}
    with open(FIX / "tls-parameters-8.csv", newline="") as fh:
        for row in csv.DictReader(fh):
            value, name = row["Value"].strip(), row["Description"].strip()
            if value.isdigit() and name and name not in ("Reserved", "Unassigned") and not name.startswith("Reserved"):
                out[int(value)] = re.sub(r"\s*\(.*\)$", "", name)  # "X25519Kyber768Draft00 (OBSOLETE)" -> the name
    return out


def main() -> None:
    s, o, g = suites(), openssl_names(), groups()
    for code, (std, _ossl) in o.items():
        if s.get(code) != std:
            raise SystemExit(f"OpenSSL stdname for 0x{code:04X} ({std}) differs from IANA ({s.get(code)})")
    sources = {"tls-parameters-4.csv": _sha(FIX / "tls-parameters-4.csv"),
               "tls-parameters-8.csv": _sha(FIX / "tls-parameters-8.csv"),
               "openssl-3.5.7-ciphers-V-stdname.txt": _sha(FIX / "openssl-3.5.7-ciphers-V-stdname.txt")}
    lines = [
        '"""TLS registry tables: every IANA cipher suite and supported group, and OpenSSL\'s suite names.',
        "",
        "GENERATED by scan_node/scripts/gen_tls_registry.py from the IANA TLS registries (cipher suites, supported groups;",
        "fetched 2026-11-12) and OpenSSL 3.5.7 `openssl ciphers -V -stdname`. Do not edit by hand: change the inputs in",
        "scan_node/tests/fixtures/iana/ and run the generator. The backend's copy is",
        "backend/utilities/cbom_sources/data/tls_cipher_suites.json (a test keeps the two equal).",
        '"""',
        "from __future__ import annotations",
        "",
        f"SOURCES = {json.dumps(sources, indent=4, sort_keys=True)}",
        "",
        "# code -> IANA name (every assigned single-codepoint suite; the SCSV signalling values are not suites)",
        "SUITES: dict[int, str] = {",
        *[f'    0x{c:04X}: "{n}",' for c, n in sorted(s.items())],
        "}",
        "",
        "# code -> OpenSSL name (what `openssl s_client` prints) for the suites OpenSSL 3.5.7 implements",
        "OPENSSL_NAMES: dict[int, str] = {",
        *[f'    0x{c:04X}: "{v[1]}",' for c, v in sorted(o.items())],
        "}",
        "",
        "# code -> IANA name of every assigned TLS supported group (named curves, FFDHE, ML-KEM and hybrids)",
        "GROUP_NAMES: dict[int, str] = {",
        *[f'    {c}: "{n}",' for c, n in sorted(g.items())],
        "}",
        "",
        "# TLS 1.3 suites are the ones without a key exchange in the name (RFC 8446 B.4 and later registrations)",
        "TLS13_SUITES: tuple[int, ...] = tuple(c for c, n in sorted(SUITES.items()) if \"_WITH_\" not in n)",
        "# TLS 1.2 and older: every suite with a key exchange, except TLS_NULL_WITH_NULL_NULL (never negotiable)",
        "LEGACY_SUITES: tuple[int, ...] = tuple(c for c, n in sorted(SUITES.items()) if \"_WITH_\" in n and c != 0x0000)",
        "_BY_NAME: dict[str, int] = {**{n: c for c, n in OPENSSL_NAMES.items()}, **{n: c for c, n in SUITES.items()}}",
        "",
        "",
        "def suite_code(name: str | None) -> int | None:",
        '    """The code of a suite named the IANA way or the OpenSSL way (s_client), or None."""',
        "    if not name:",
        "        return None",
        "    return _BY_NAME.get(str(name).strip())",
        "",
        "",
        "def suite_name(code: int) -> str:",
        '    """The IANA name of a suite code; an unassigned code is shown as its hex value."""',
        '    return SUITES.get(code, f"0x{code:04X}")',
        "",
        "",
        "def code_hex(code: int) -> str:",
        '    return f"0x{code:04X}"',
        "",
        "",
        "def group_name(code: int) -> str:",
        '    return GROUP_NAMES.get(code, f"0x{code:04X}")',
        "",
    ]
    NODE_OUT.write_text("\n".join(lines))
    BACKEND_OUT.write_text(json.dumps({
        "_comment": "GENERATED by scan_node/scripts/gen_tls_registry.py (same table as scan_node/zs_scan_node/tls_registry.py)",
        "sources": sources,
        "suites": {f"0x{c:04X}": {"iana": n, **({"openssl": o[c][1]} if c in o else {})} for c, n in sorted(s.items())},
        "groups": {str(c): n for c, n in sorted(g.items())},
    }, indent=1, sort_keys=True) + "\n")
    print(f"{len(s)} suites ({len(o)} with OpenSSL names), {len(g)} groups -> {NODE_OUT.name}, {BACKEND_OUT.name}")


if __name__ == "__main__":
    main()
