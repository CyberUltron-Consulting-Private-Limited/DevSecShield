/**
 * F5 (CB-38 PR-6): the AI panel is absent unless the backend says the assistant is available; badge, egress note,
 * citation chips and outcome notes.
 * Run: npx --yes tsx --test components/cbom/results/aiPanelLogic.test.ts
 */
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { test } from "node:test";
import { aiPanelVisible, answerBadge, canAsk, citationLabel, egressNote, outcomeNote } from "./aiPanelLogic";

test("unavailable, unknown or failed status renders nothing", () => {
  assert.equal(aiPanelVisible(undefined), false);
  assert.equal(aiPanelVisible(null), false);
  assert.equal(aiPanelVisible({ available: false }), false);
  assert.equal(aiPanelVisible({ available: true, provider: "bedrock", model: "m" }), true);
  assert.equal(egressNote({ available: false }), "");
});

test("the component returns null before any markup when the panel is not visible", () => {
  const src = fs.readFileSync(path.join(__dirname, "AiRemediationPanel.tsx"), "utf8");
  const gate = src.indexOf("if (!aiPanelVisible(status.data)) return null;");
  assert.ok(gate > 0, "the visibility gate is missing");
  assert.ok(gate < src.indexOf("data-testid=\"cbom-ai-panel\""), "markup is built before the gate");
  assert.ok(!src.includes("dangerouslySetInnerHTML"), "answers are text only");
  assert.ok(src.includes("export default function AiRemediationPanel"));
});

test("egress note names exactly where data goes", () => {
  assert.equal(
    egressNote({ available: true, provider: "bedrock", region: "ap-south-1", model: "openai.gpt-oss-120b-1:0",
      egress: [{ host: "bedrock-runtime.ap-south-1.amazonaws.com", port: 443, purpose: "x" }] }),
    "Uses AWS Bedrock (ap-south-1, openai.gpt-oss-120b-1:0) · outbound HTTPS to bedrock-runtime.ap-south-1.amazonaws.com only",
  );
  assert.equal(
    egressNote({ available: true, provider: "openai_compat", model: "qwen3:8b", egress: [{ host: "ollama.internal", port: 11434, purpose: "x" }] }),
    "Uses qwen3:8b on your deployment (ollama.internal) · nothing leaves your network",
  );
});

test("badge, citation labels, outcomes and the question rule", () => {
  assert.equal(answerBadge({ model: "qwen3:8b", kb_version: "2026.11.10.1", provider: "openai_compat" }),
    "Generated by qwen3:8b on your deployment · checked against KB 2026.11.10.1");
  assert.equal(answerBadge({ model: "m", kb_version: "1", provider: "bedrock", region: "ap-south-1" }),
    "Generated by m on AWS Bedrock (ap-south-1) · checked against KB 1");
  const items = [{ id: "K1.s2", label: "K1 PROTO_TLS10 · step 2 (Apache httpd)" }];
  assert.equal(citationLabel("K1.s2", items), "K1 PROTO_TLS10 · step 2 (Apache httpd)");
  assert.equal(citationLabel("F9", items), "F9");
  const base = { summary: "", steps: [], commands: [], caveats: [], dropped_commands: 0, model: "m", kb_version: "1", prompt_version: "p", items: [] };
  assert.equal(outcomeNote({ ...base, status: "ok" }), null);
  const withheld = outcomeNote({ ...base, status: "withheld", withheld_reason: "AI answer withheld: it named an identifier not in the knowledge base" });
  assert.ok(withheld && withheld.text.includes("not in the knowledge base") && withheld.text.includes("knowledge-base steps"));
  assert.ok(outcomeNote({ ...base, status: "timeout" })!.text.includes("did not answer in time"));
  assert.equal(canAsk("plan", ""), true);
  assert.equal(canAsk("question", "   "), false);
  assert.equal(canAsk("question", "x".repeat(501)), false);
  assert.equal(canAsk("question", "which step applies to nginx?"), true);
});
