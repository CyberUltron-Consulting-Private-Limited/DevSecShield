"""TLS cipher suite names: one IANA name and code per suite, whatever spelling a collector stored.

Collectors store suites under different names for the same code point: openssl ``s_client`` prints OpenSSL names
(``ECDHE-RSA-AES128-SHA``), the raw probes (``zs_scan_node.tlsprobe``) and IANA-aware collectors print the IANA registry
name (``TLS_ECDHE_RSA_WITH_AES_128_CBC_SHA``), Java and SSLv3-era tools the ``SSL_`` spelling, and a database reports its
server's OpenSSL name. The export lists each accepted suite once, by its IANA name, with its two-byte code (CycloneDX
``cipherSuites[].identifiers``), so the same server reads the same whichever collector, version or row age.

The table is ``data/tls_cipher_suites.json``, generated by ``scripts/tls_suites/build_table.py`` from the IANA registry
and OpenSSL's own name lists (vendored in ``scripts/tls_suites/sources``). It is the one OpenSSL->IANA table of the
product: a collector that needs it copies the file byte for byte (a test keeps copies equal).
"""
from __future__ import annotations

import json
import os
from functools import lru_cache

DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "tls_cipher_suites.json")
# what tools print when there is no suite or group: never a name (openssl s_client "Cipher is (NONE)",
# "Negotiated TLS1.3 group: <NULL>", Perl/Net::SSLeay "undef")
SENTINELS = frozenset({"<null>", "(null)", "null", "none", "(none)", "undef", "n/a", "-"})


@lru_cache(maxsize=1)
def _index() -> dict[str, tuple[str, str]]:
    """Upper-cased IANA, ``SSL_`` and OpenSSL names -> (IANA name, code ``0xC0,0x13``)."""
    with open(DATA, encoding="utf-8") as fh:
        suites = json.load(fh)["suites"]
    out: dict[str, tuple[str, str]] = {}
    for entry in suites:
        value = (entry["iana"], entry["code"])
        names = [entry["iana"], *entry["openssl"]]
        if entry["iana"].startswith("TLS_"):
            names.append("SSL_" + entry["iana"][4:])
        for name in names:
            out.setdefault(name.upper(), value)
    return out


def is_sentinel(name: str) -> bool:
    return name.strip().lower() in SENTINELS


def canonical(name: str) -> tuple[str, str | None]:
    """(IANA name, code) of the suite ``name`` (IANA, OpenSSL or ``SSL_`` spelling, any case); a name the table does
    not hold comes back as given, with no code."""
    hit = _index().get(name.strip().upper())
    return hit if hit is not None else (name, None)


def identifiers(code: str | None) -> list[str]:
    """CycloneDX ``cipherSuites[].identifiers``: the code's two bytes (``["0xC0", "0x13"]``)."""
    return code.split(",") if code else []


__all__ = ["DATA", "SENTINELS", "canonical", "identifiers", "is_sentinel"]
