"""The launcher and the per-tool wrappers that run zs-collect, rendered for one verified release.  Standard library only.

Canonical copy: ``scan_node/zs_scan_node/transports/wrappers.py``.  A byte-identical copy lives at
``backend/utilities/cbom_sources/transports/wrappers.py`` (the backend serves these as transport artifacts); a backend
test compares the two files, so change both or neither.

* ``render_wrapper``: the POSIX sh launcher.  It copies the mirrored binary into a private ``mktemp -d``, refuses it
  unless its sha256 is the signed manifest's (baked in per architecture), verifies the mirrored manifest's Ed25519
  signature with OpenSSL 3 when present, runs it with ``--tmp-dir`` set to that directory and removes it.
* ``render_ansible``: a playbook for an AWX/AAP job template (``ansible.builtin.script`` runs the launcher; the
  output comes back as one ``debug`` event per <= 384 KB chunk, because AWX truncates large event data).
* ``render_salt``: ``zeroshield/zs_collect.sls`` (state mode) and the launcher as ``salt://zeroshield/zs-collect-run.sh``
  (``cmd.script`` mode).
* ``render_ssm_document``: a ``devsecshield-*`` Command document (``aws:runShellScript``) whose parameters SSM checks
  against an allowed pattern before it substitutes them.
Every wrapper passes only a validated nonce (16-128 of ``A-Za-z0-9_-``), tier (1 or 2) and per-host timeout
(``--timeout-s``, 10-3600 seconds: the source's ``timeout_s``, so a customer who raises it for slow hosts changes what
zs-collect does on the host) to the launcher.
"""
from __future__ import annotations

import json
import re

NONCE_PATTERN = "^[A-Za-z0-9_-]{16,128}$"
TIMEOUT_PATTERN = "^([1-9][0-9]|[1-9][0-9][0-9]|[1-2][0-9][0-9][0-9]|3[0-5][0-9][0-9]|3600)$"  # 10..3600 seconds
DEFAULT_TIMEOUT_S = 300
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.]+)?$")
SSM_DOCUMENT_RE = re.compile(r"^devsecshield-[A-Za-z0-9_.-]{1,115}$")


WRAPPER = r"""#!/bin/sh
# zs-collect launcher for release @VERSION@ (generated by ZeroShield; do not edit).
# It copies the binary into a private temp dir, refuses it unless its sha256 is the signed manifest's, verifies the
# mirrored manifest's Ed25519 signature with OpenSSL 3 when the manifest is present, runs it, and removes the temp dir.
# Exit 3: binary missing or unsupported machine; exit 4: integrity check failed; otherwise zs-collect's own status.
set -u
umask 077
ZS_DIR="${ZS_COLLECT_DIR:-/opt/zeroshield/zs-collect}"
case "$(uname -m)" in
  x86_64|amd64) ZS_ARCH=amd64; ZS_SHA="@SHA_AMD64@" ;;
  aarch64|arm64) ZS_ARCH=arm64; ZS_SHA="@SHA_ARM64@" ;;
  *) echo "zs-collect: unsupported machine $(uname -m)" >&2; exit 3 ;;
esac
if [ -z "$ZS_SHA" ]; then echo "zs-collect: release @VERSION@ has no $ZS_ARCH build" >&2; exit 3; fi
ZS_NAME="zs-collect-@VERSION@-linux-$ZS_ARCH"
ZS_TMP="$(mktemp -d "${TMPDIR:-/tmp}/zs-collect.XXXXXXXX")" || { echo "zs-collect: mktemp failed" >&2; exit 3; }
trap 'rm -rf "$ZS_TMP"' EXIT
trap 'exit 130' INT TERM HUP
chmod 0700 "$ZS_TMP"
if ! cp "$ZS_DIR/$ZS_NAME" "$ZS_TMP/zs-collect" 2>/dev/null; then
  echo "zs-collect: $ZS_DIR/$ZS_NAME is missing (mirror release @VERSION@ there)" >&2; exit 3
fi
if ! printf '%s  %s\n' "$ZS_SHA" "$ZS_TMP/zs-collect" | sha256sum -c --status - 2>/dev/null; then
  echo "zs-collect: checksum mismatch for $ZS_NAME; refusing to run it" >&2; exit 4
fi
ZS_MANIFEST="$ZS_DIR/zs-collect-@VERSION@.manifest.json"
if [ -f "$ZS_MANIFEST" ] && command -v openssl >/dev/null 2>&1 && openssl version 2>/dev/null | grep -q '^OpenSSL [3-9]'; then
  cat > "$ZS_TMP/release.pub" <<'ZS_PUB_EOF'
@PUBLIC_PEM@ZS_PUB_EOF
  printf '%s' '@SIG_B64@' | openssl base64 -d -A > "$ZS_TMP/manifest.sig" 2>/dev/null
  if ! openssl pkeyutl -verify -rawin -pubin -inkey "$ZS_TMP/release.pub" -in "$ZS_MANIFEST" \
       -sigfile "$ZS_TMP/manifest.sig" >/dev/null 2>&1; then
    echo "zs-collect: the mirrored manifest's signature is not valid; refusing to run" >&2; exit 4
  fi
  if ! grep -q "$ZS_SHA" "$ZS_MANIFEST"; then
    echo "zs-collect: the mirrored manifest does not list this binary; refusing to run" >&2; exit 4
  fi
fi
chmod 0500 "$ZS_TMP/zs-collect"
TMPDIR="$ZS_TMP" "$ZS_TMP/zs-collect" --tmp-dir "$ZS_TMP" "$@"
exit $?
"""


def render_wrapper(manifest: dict, public_pem: str, sig_b64: str) -> str:
    """The launcher for one verified release (sha256 per arch baked in)."""
    version = str(manifest["version"])
    if not VERSION_RE.match(version):
        raise ValueError("bad version")
    sha = {f["arch"]: f["sha256"] for f in manifest.get("files") or []}
    for value in sha.values():
        if not re.fullmatch(r"[0-9a-f]{64}", value):
            raise ValueError("bad sha256")
    sig = sig_b64.strip()
    if not re.fullmatch(r"[A-Za-z0-9+/=]{40,200}", sig):
        raise ValueError("bad signature encoding")
    pem = public_pem.strip() + "\n"
    if not re.fullmatch(r"-----BEGIN PUBLIC KEY-----\n[A-Za-z0-9+/=\n]+-----END PUBLIC KEY-----\n", pem):
        raise ValueError("bad public key")
    return (WRAPPER.replace("@VERSION@", version).replace("@SHA_AMD64@", sha.get("amd64", ""))
            .replace("@SHA_ARM64@", sha.get("arm64", "")).replace("@PUBLIC_PEM@", pem).replace("@SIG_B64@", sig))




def timeout_arg(value) -> int:
    """zs-collect's ``--timeout-s`` (10..3600), or ValueError: it reaches a shell on every host."""
    if isinstance(value, bool) or not isinstance(value, int) or not 10 <= value <= 3600:
        raise ValueError("the per-host timeout must be 10..3600 seconds")
    return value


def host_timeout(options) -> int:
    """The ``--timeout-s`` a transport passes for ``options`` (a CollectOptions): the source's per-host timeout,
    clamped into zs-collect's 10..3600."""
    return timeout_arg(max(10, min(3600, int(getattr(options, "timeout_per_target_s", 0) or DEFAULT_TIMEOUT_S))))


def _check_launcher(launcher: str) -> str:
    if not launcher.startswith("#!/bin/sh\n") or "ZS_LAUNCHER_EOF" in launcher:
        raise ValueError("not a zs-collect launcher")
    return launcher


ANSIBLE_PLAYBOOK = """# ZeroShield zs-collect, release @VERSION@ (generated by ZeroShield; do not edit).
# AWX/AAP job template: this playbook (with files/zs-collect-run.sh next to it), privilege escalation on (zs-collect
# drops from root to zs-cbom itself), and "Prompt on launch" for Limit and for Variables. ZeroShield launches it with
# limit=<the hosts of one batch> and extra_vars zs_nonce, zs_tier and zs_timeout_s, then reads the debug events below.
# The binary, manifest and signature of release @VERSION@ must be mirrored to /opt/zeroshield/zs-collect on each host.
- name: ZeroShield zs-collect @VERSION@
  hosts: all
  gather_facts: false
  become: true
  vars:
    zs_chunk_bytes: 393216
  tasks:
    - name: zs-collect inputs
      ansible.builtin.assert:
        that:
          - zs_nonce is defined
          - zs_nonce is string
          - zs_nonce is match('^[A-Za-z0-9_-]{16,128}$')
          - (zs_tier | default(1) | int) in [1, 2]
          - (zs_timeout_s | default(300) | int) >= 10
          - (zs_timeout_s | default(300) | int) <= 3600
        quiet: true
    # the raw output is not logged here (it is the whole document twice); the next two tasks carry it
    - name: zs-collect
      ansible.builtin.script: "zs-collect-run.sh --nonce {{ zs_nonce }} --tier {{ zs_tier | default(1) | int }} --timeout-s {{ zs_timeout_s | default(300) | int }} --output chunks --chunk-bytes {{ zs_chunk_bytes | int }}"
      register: zs_out
      no_log: true
      failed_when: false
      changed_when: false
    - name: zs-collect status
      ansible.builtin.debug:
        msg: "ZSRC {{ zs_out.rc | default(-1) }} {{ (zs_out.stderr | default(''))[-2000:] | replace('\\n', ' ') }}"
    - name: zs-collect output
      ansible.builtin.debug:
        msg: "{{ zs_out.stdout_lines[item] }}"
      loop: "{{ range(zs_out.stdout_lines | default([]) | length) | list }}"
      loop_control:
        label: "chunk {{ item + 1 }}"
"""


def render_ansible(version: str, launcher: str) -> dict[str, str]:
    """``{path: content}`` for an AWX/AAP project: the playbook and ``files/zs-collect-run.sh``."""
    if not VERSION_RE.match(version):
        raise ValueError("bad version")
    return {"zs-collect.yml": ANSIBLE_PLAYBOOK.replace("@VERSION@", version),
            "files/zs-collect-run.sh": _check_launcher(launcher)}


SALT_STATE = """{#- ZeroShield zs-collect, release @VERSION@ (generated by ZeroShield; do not edit).
    salt-api runs it as state.apply zeroshield.zs_collect with pillar
    {"zs_nonce": ..., "zs_tier": 1|2, "zs_timeout_s": 10..3600}.

    Master sizing (salt-api client "ssh", salt-ssh): the master runs up to ssh_max_procs salt-ssh processes at once,
    about 80 MB each (50 processes OOM-killed a 768 MB master in ZeroShield's lab), so give the master about
    512 MB + 80 MB x ssh_max_procs.  One salt-ssh batch is one synchronous salt-api request: keep
    batch_size / ssh_max_procs x the per-host time within the transport's timeout_s (ZeroShield accepts a batch of at
    most 100 for salt-ssh; 50, the default, took about 240 s per batch on a loaded 4-vCPU master).
    Minions (clients local / local_async) do not load the master this way. #}
{%- set nonce = salt['pillar.get']('zs_nonce', '') | string %}
{%- set tier = salt['pillar.get']('zs_tier', 1) | int %}
{%- set timeout_s = salt['pillar.get']('zs_timeout_s', 300) | int %}
{%- if nonce | regex_match('^([A-Za-z0-9_-]{16,128})$') and tier in [1, 2] and 10 <= timeout_s <= 3600 %}
zs_collect:
  cmd.script:
    - source: salt://zeroshield/zs-collect-run.sh
    - args: --nonce {{ nonce }} --tier {{ tier }} --timeout-s {{ timeout_s }} --output json
    - success_retcodes: [1, 2]
{%- else %}
zs_collect:
  test.fail_without_changes:
    - name: zs-collect needs the pillar values zs_nonce (16-128 of A-Za-z0-9_-), zs_tier (1 or 2) and zs_timeout_s (10-3600)
{%- endif %}
"""


def render_salt(version: str, launcher: str) -> dict[str, str]:
    """``{path: content}`` under the master's file roots: the state and the launcher (``cmd.script`` mode)."""
    if not VERSION_RE.match(version):
        raise ValueError("bad version")
    return {"zeroshield/zs_collect.sls": SALT_STATE.replace("@VERSION@", version),
            "zeroshield/zs-collect-run.sh": _check_launcher(launcher)}


def salt_args(nonce: str, tier: int, output: str = "json", timeout_s: int = DEFAULT_TIMEOUT_S) -> str:
    """The launcher arguments for ``cmd.script`` (validated: they reach a shell on every minion)."""
    if not re.fullmatch(NONCE_PATTERN[1:-1], nonce or "") or tier not in (1, 2) or output not in ("json", "chunks"):
        raise ValueError("bad zs-collect arguments")
    return f"--nonce {nonce} --tier {tier} --timeout-s {timeout_arg(timeout_s)} --output {output}"


def render_ssm_document(version: str, launcher: str) -> dict:
    """The Command document (schema 2.2).  The launcher is written to a private temp file and run; its exit status
    for a collected or refused host (0, 1, 2: a document was printed) becomes 0, so SSM keeps the output either way;
    3 and 4 (binary missing, integrity check failed) stay failures.  ``output=chunks`` makes the document one
    gzip+base64 line (small fleets can then read it inline, under GetCommandInvocation's 24,000 characters)."""
    if not VERSION_RE.match(version):
        raise ValueError("bad version")
    lines = ["set -u", "umask 077",
             'ZS_L="$(mktemp "${TMPDIR:-/tmp}/zs-collect-run.XXXXXXXX")" || { echo "zs-collect: mktemp failed" >&2; exit 3; }',
             "trap 'rm -f \"$ZS_L\"' EXIT",
             "cat > \"$ZS_L\" <<'ZS_LAUNCHER_EOF'"]
    lines += _check_launcher(launcher).rstrip("\n").split("\n")
    lines += ["ZS_LAUNCHER_EOF",
              "/bin/sh \"$ZS_L\" --nonce '{{ nonce }}' --tier '{{ tier }}' --timeout-s '{{ timeout }}' --output '{{ output }}'",
              "rc=$?",
              'echo "ZSRC $rc" >&2',
              'if [ "$rc" -le 2 ]; then exit 0; fi',
              'exit "$rc"']
    return {
        "schemaVersion": "2.2",
        "description": f"ZeroShield zs-collect {version}: read-only CBOM collection of this host (generated; do not edit)",
        "parameters": {
            "nonce": {"type": "String", "allowedPattern": NONCE_PATTERN,
                      "description": "Run nonce from ZeroShield (echoed in the output)"},
            "tier": {"type": "String", "allowedValues": ["1", "2"], "default": "1",
                     "description": "1: unprivileged reads; 2: also the zs-cbom sudoers checks"},
            "timeout": {"type": "String", "allowedPattern": TIMEOUT_PATTERN, "default": str(DEFAULT_TIMEOUT_S),
                        "description": "Per-host timeout of zs-collect, 10-3600 seconds (the source's timeout_s)"},
            "output": {"type": "String", "allowedValues": ["json", "chunks"], "default": "json",
                       "description": "json, or one gzip+base64 line (chunks)"},
        },
        "mainSteps": [{
            "action": "aws:runShellScript", "name": "zsCollect",
            "precondition": {"StringEquals": ["platformType", "Linux"]},
            # above zs-collect's own longest run (--timeout-s 3600 + its 60 s of command slack + the launcher)
            "inputs": {"timeoutSeconds": "3900", "runCommand": lines},
        }],
    }


def ssm_document_json(version: str, launcher: str) -> str:
    return json.dumps(render_ssm_document(version, launcher), indent=1) + "\n"
