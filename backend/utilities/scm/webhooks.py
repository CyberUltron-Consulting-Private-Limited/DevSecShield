"""Inbound SCM webhooks: signature checks and what each event does.

Every connection has its own webhook URL (``/scm/webhooks/<provider>/<webhook_uid>``) and its own secret, generated by
ZeroShield, shown once, stored encrypted (HMAC verification needs the secret itself). A request is processed only
after its signature verifies against the raw body:

    GitHub     ``X-Hub-Signature-256: sha256=<hex HMAC-SHA256(secret, body)>`` (org webhook or the App's webhook)
    GitLab     ``X-Gitlab-Token: <secret>`` (group webhook; GitLab sends the token, not a signature)
    Bitbucket  ``X-Hub-Signature: sha256=<hex HMAC-SHA256(secret, body)>`` (workspace webhook with a secret)

Comparisons are constant-time. Events:

* push to the policy branch (default: the repository's default branch) of an in-scope repository whose policy has
  "scan on push" -> the policy's products are queued at push priority and charged once per commit
  (``queue.enqueue_push``). Tag pushes, branch deletions and other branches are acknowledged and ignored.
* GitHub ``repository`` (created, renamed, archived, ...) -> that repository is upserted from the payload; ``deleted``
  marks it removed. ``installation_repositories`` and an unknown repository in a push ask for a sync of the
  connection (the scheduler runs it within a tick).
* Redeliveries and replays are harmless: the push run is keyed on (repository, branch, commit).
"""
from __future__ import annotations

import datetime as dt
import hashlib
import hmac
from dataclasses import dataclass
from typing import Any

from sqlmodel import Session, select

from backend.utilities.scm.common import log
from backend.utilities.scm.inventory import filter_input, filters_of, upsert_repo
from backend.utilities.scm.models import ScmConnection, ScmRepository
from backend.utilities.scm.policies import team_policies, winning_policy
from backend.utilities.scm.providers import github as gh_provider

MAX_BODY = 5 * 1024 * 1024
ZERO_SHA = "0" * 40


def _hmac_ok(secret: str, body: bytes, header: str | None) -> bool:
    if not secret or not header or not header.startswith("sha256="):
        return False
    expected = "sha256=" + hmac.new(secret.encode(), body, hashlib.sha256).hexdigest()
    return hmac.compare_digest(expected.encode(), header.strip().encode())


def verify(provider: str, secret: str, body: bytes, headers: Any) -> bool:
    if provider == "github":
        return _hmac_ok(secret, body, headers.get("x-hub-signature-256"))
    if provider == "bitbucket":
        return _hmac_ok(secret, body, headers.get("x-hub-signature"))
    if provider == "gitlab":
        token = headers.get("x-gitlab-token") or ""
        return bool(secret) and bool(token) and hmac.compare_digest(secret.encode(), token.encode())
    return False


def sign_github(secret: str, body: bytes) -> str:
    return "sha256=" + hmac.new(secret.encode(), body, hashlib.sha256).hexdigest()


@dataclass
class Push:
    external_id: str
    full_name: str
    branch: str
    sha: str


def _branch(ref: Any) -> str | None:
    ref = str(ref or "")
    return ref[len("refs/heads/"):] if ref.startswith("refs/heads/") else None


def parse(provider: str, event: str, payload: dict[str, Any]) -> tuple[str, Any]:
    """(kind, data): kind is push | repository | resync | ping | ignored."""
    if provider == "github":
        if event == "ping":
            return "ping", None
        if event == "push":
            branch, sha = _branch(payload.get("ref")), str(payload.get("after") or "")
            repo = payload.get("repository") or {}
            if not branch or payload.get("deleted") or not sha or sha == ZERO_SHA:
                return "ignored", "not a branch push"
            return "push", [Push(str(repo.get("id")), str(repo.get("full_name") or ""), branch, sha)]
        if event == "repository":
            return "repository", (str(payload.get("action") or ""), payload.get("repository") or {})
        if event in ("installation_repositories", "installation"):
            return "resync", None
        return "ignored", f"event {event[:40]}"
    if provider == "gitlab":
        kind = str(payload.get("object_kind") or "")
        if kind != "push":
            return "ignored", f"event {kind[:40]}"
        branch, sha = _branch(payload.get("ref")), str(payload.get("after") or payload.get("checkout_sha") or "")
        project = payload.get("project") or {}
        if not branch or not sha or sha == ZERO_SHA:
            return "ignored", "not a branch push"
        return "push", [Push(str(payload.get("project_id") or project.get("id")),
                             str(project.get("path_with_namespace") or ""), branch, sha)]
    if provider == "bitbucket":
        if event != "repo:push":
            return "ignored", f"event {event[:40]}"
        repo = payload.get("repository") or {}
        pushes = []
        for change in ((payload.get("push") or {}).get("changes") or []):
            new = change.get("new") or {}
            if new.get("type") != "branch" or change.get("closed"):
                continue
            sha = str((new.get("target") or {}).get("hash") or "")
            if new.get("name") and sha:
                pushes.append(Push(str(repo.get("uuid") or ""), str(repo.get("full_name") or ""), str(new["name"]), sha))
        return ("push", pushes) if pushes else ("ignored", "not a branch push")
    return "ignored", "unknown provider"


def handle(engine: Any, connection_id: int, provider: str, event: str, payload: dict[str, Any],
           now: dt.datetime) -> dict[str, Any]:
    from backend.utilities.scm import queue as Q

    kind, data = parse(provider, event, payload)
    if kind in ("ping", "ignored"):
        return {"status": kind, "reason": data}
    with Session(engine) as session:
        connection = session.get(ScmConnection, connection_id)
        if connection is None or not connection.enabled:
            return {"status": "ignored", "reason": "connection disabled"}
        if kind == "resync":
            connection.next_sync_at, connection.sync_requested_at = now, now
            session.add(connection)
            session.commit()
            return {"status": "resync_requested"}
        if kind == "repository":
            action, repo_json = data
            ext = str(repo_json.get("id"))
            existing = session.exec(select(ScmRepository).where(ScmRepository.connection_id == connection_id,
                                                                ScmRepository.external_id == ext)).first()
            if action == "deleted":
                if existing is not None and existing.removed_at is None:
                    existing.removed_at = now
                    existing.in_scope, existing.scope_reason = False, "removed"
                    session.add(existing)
                    session.commit()
                return {"status": "repository_removed"}
            found = gh_provider.normalise(repo_json)
            _row, outcome = upsert_repo(session, connection, found, now, filters_of(connection), existing)
            session.commit()
            return {"status": f"repository_{outcome}"}
        results = []
        policies = team_policies(session, connection.team_id)
        for push in data:
            repo = session.exec(select(ScmRepository).where(ScmRepository.connection_id == connection_id,
                                                            ScmRepository.external_id == push.external_id)).first()
            if repo is None:
                connection.next_sync_at, connection.sync_requested_at = now, now
                session.add(connection)
                results.append({"repo": push.full_name[:120], "status": "unknown_repository_sync_requested"})
                continue
            if not repo.in_scope or repo.removed_at is not None:
                results.append({"repo": repo.full_name, "status": "out_of_scope"})
                continue
            policy, _why = winning_policy(filter_input(repo), policies, repo.policy_id)
            if policy is None or not policy.on_push:
                results.append({"repo": repo.full_name, "status": "no_push_policy"})
                continue
            target = policy.branch or repo.default_branch
            if push.branch != target:
                results.append({"repo": repo.full_name, "status": "other_branch"})
                continue
            out = Q.enqueue_push(session, repo, products=policy.products, branch=push.branch, commit_sha=push.sha,
                                 owner_user_id=policy.owner_user_id or connection.owner_user_id, now=now)
            status = ("insufficient_credits" if out["insufficient"] else "queued" if out["queued"]
                      else "duplicate" if out["duplicates"] else "nothing_to_queue")
            results.append({"repo": repo.full_name, "status": status, "queued": len(out["queued"])})
        session.commit()
    log("webhook push", connection=connection_id, provider=provider,
        queued=sum(r.get("queued", 0) for r in results))
    return {"status": "processed", "pushes": results}


__all__ = ["MAX_BODY", "handle", "parse", "sign_github", "verify"]
