from typing import TypedDict, Literal, List, Optional
from datetime import datetime

# Conversation types
ConversationType = Literal[
    "sast",
    "sbom_sca",
    "iac",
    "gitleaks",
    "discovery",
    "llm",
    "mcp",
    "dast"
]

# Message/Active context types
MessageType = Literal["message", "tool"]
SenderType = Literal["user", "agent"]


class Conversation(TypedDict, total=False):
    """TypedDict for Conversations collection
    
    Note: _id is optional as it's auto-generated by MongoDB when creating new documents.
    When reading from MongoDB, _id will always be present.
    All fields are optional to allow for flexible MongoDB operations (create, update, partial reads).
    """
    _id: str  # MongoDB ObjectId as string (auto-generated, always present when reading)
    user_id: int
    messages: List[str]  # Array of message _ids in order (earliest to latest)
    created_at: datetime
    conv_type: ConversationType
    title: str


class MessageLog(TypedDict, total=False):
    """TypedDict for Message log collection
    
    Note: _id is optional as it's auto-generated by MongoDB when creating new documents.
    When reading from MongoDB, _id will always be present.
    parent_id can be None for root messages.
    All fields are optional to allow for flexible MongoDB operations (create, update, partial reads).
    """
    _id: str  # MongoDB ObjectId as string (auto-generated, always present when reading)
    conversation_id: str  # or UUID (to be determined)
    parent_id: Optional[str]  # Parent message _id (can be None for root messages)
    user_id: int
    content: str
    created_at: datetime
    type: MessageType
    sender: SenderType


class ActiveContextLog(TypedDict, total=False):
    """TypedDict for Active context log collection
    
    Note: _id is optional as it's auto-generated by MongoDB when creating new documents.
    When reading from MongoDB, _id will always be present.
    parent_id can be None for root contexts.
    All fields are optional to allow for flexible MongoDB operations (create, update, partial reads).
    """
    _id: str  # MongoDB ObjectId as string (auto-generated, always present when reading)
    conversation_id: str  # or UUID (to be determined)
    parent_id: Optional[str]  # Parent active context _id (can be None for root contexts)
    user_id: int
    content: str
    created_at: datetime
    type: MessageType
    sender: SenderType
    title: str

